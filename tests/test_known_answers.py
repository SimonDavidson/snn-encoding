@pytest.mark.parametrize("signal_name", ["noise", "chirp", "sine", "ramp"])
def test_T2_1_reconstruction_error_is_bounded_by_C(signal_name):
    """Equation (16): |u(t) - r(t)| < C, always. This is a theorem, not a
    tolerance. The reference is reconstructed from the event stream alone,
    which is what a downstream user of the release would do."""
    C = 0.1
    n = int(1.0 / DT)
    t = np.arange(n) * DT
    if signal_name == "noise":
        u = np.cumsum(np.random.default_rng(0).standard_normal(n)) * 0.01
    elif signal_name == "chirp":
        u = np.sin(2 * np.pi * (5 + 40 * t) * t)
    elif signal_name == "sine":
        u = 2.0 * np.sin(2 * np.pi * 7 * t)
    else:
        u = 3.0 * t
    drive = u[None, :]

    enc = E.SendOnDelta(n_channels=1, C=C, refractory=0.0,
                        reference_update="lattice")
    train = enc.encode_from_drive(drive, DT)

    # r(t) = u[0] + C * (cumulative signed event count)
    r = np.full(n, u[0])
    idx = np.clip(np.round(train.time / DT).astype(int), 0, n - 1)
    steps = np.zeros(n)
    np.add.at(steps, idx, C * train.polarity.astype(float))
    r = u[0] + np.cumsum(steps)

    err = np.max(np.abs(u - r))
    assert err < C + 1e-9, f"{signal_name}: max reconstruction error {err:.6f} >= C={C}"


def test_T2_2_event_count_follows_total_variation():
    """Equation (17): N = (1/C) * integral |du/dt| dt.

    For u = A sin(2*pi*f*t) the total variation over duration D is 4*A*f*D.
    With A=1, f=5, D=2: TV = 40, so N = 40/C = 400 at C=0.1.
    Tolerance allows one lost event per turning point (2*f*D = 20 of them).
    """
    A, f, D, C = 1.0, 5.0, 2.0, 0.1
    predicted = 4 * A * f * D / C
    slack = 2 * f * D + 2
    enc = E.SendOnDelta(n_channels=1, C=C, refractory=0.0)
    n = len(enc.encode_from_drive(sine_drive(A, f, n_channels=1, duration=D), DT))
    assert predicted - slack <= n <= predicted + slack, (
        f"{n} events, total variation predicts {predicted:.0f} (+/- {slack:.0f})")


def test_T2_3_linear_ramp_gives_regular_intervals():
    """A ramp of slope s produces events at exactly C/s, all of one polarity.
    Sharp test of the reference-update logic. s=10, C=0.5 -> 0.05 s intervals."""
    s, C = 10.0, 0.5
    enc = E.SendOnDelta(n_channels=1, C=C, refractory=0.0)
