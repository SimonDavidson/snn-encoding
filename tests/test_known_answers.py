def test_G3_rate_parameter_is_monotonic(encoder_case):
    """Sweeping the declared rate parameter moves the event count monotonically
    in the declared direction. Without this, matched-budget comparison (§6.4)
    is not possible."""
    label, cls, kwargs = encoder_case
    drive = drive_for(cls, duration=2.0)
    base = kwargs[cls.RATE_PARAM]
    counts = []
    for factor in (0.25, 0.5, 1.0, 2.0, 4.0):
        kw = dict(kwargs)
        kw[cls.RATE_PARAM] = base * factor
        counts.append(len(cls(**kw).encode_from_drive(drive, DT, seed=0)))
    counts = np.array(counts)
    if cls.RATE_DIRECTION < 0:
        assert np.all(np.diff(counts) <= 0), f"{label} not monotonic: {counts}"
        assert counts[0] > counts[-1], f"{label} rate parameter has no effect: {counts}"
    else:
        assert np.all(np.diff(counts) >= 0), f"{label} not monotonic: {counts}"
        assert counts[-1] > counts[0], f"{label} rate parameter has no effect: {counts}"


def test_G4_time_shift_equivariance(encoder_case):
    """Delaying the drive delays every event by the same amount.

    The shift is 0.1 s = 1600 samples = an integer number of frames at the
    default 10 ms hop, so framed encoders are not disadvantaged.
    """
    label, cls, kwargs = encoder_case
    enc = cls(**kwargs)
    drive = drive_for(cls, duration=1.0)
    shift_s = 0.1
    pad = np.zeros((drive.shape[0], int(round(shift_s / DT))))
    a = enc.encode_from_drive(drive, DT, seed=7)
    b = enc.encode_from_drive(np.hstack([pad, drive]), DT, seed=7)
    assert len(a) == len(b), f"{label}: {len(a)} vs {len(b)} events after shift"
    if len(a):
        delta = np.sort(b.time) - np.sort(a.time)
        assert np.max(np.abs(delta - shift_s)) < 2 * DT


