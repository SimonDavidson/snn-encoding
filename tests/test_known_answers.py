def test_T5_1_pure_tone_below_cutoff_locks_tightly():
    """Vector strength above 0.9 for a tone the encoder is meant to lock to."""
    f = 200.0
    x = tone(f, duration=1.0)
    enc = E.PhaseLocked(n_channels=1, threshold=0.05, f_lock=1500.0,
                        refractory=0.001, mode="deterministic",
                        centre_frequencies=np.array([f]))
    train = enc.encode_from_drive(x[None, :], DT)
    vs = metrics.vector_strength(train.times_in_channel(0), f)
