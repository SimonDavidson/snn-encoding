def test_T5_3_interspike_intervals_recover_F0():
    """For a harmonic complex the pooled ISI histogram peaks at 1/F0.
    This is the one job the encoder exists to do."""
    f0 = 125.0
    x = harmonic_complex(f0, n_harmonics=8, duration=1.0)
    enc = E.PhaseLocked(n_channels=1, threshold=0.05, f_lock=1500.0,
                        refractory=0.001, mode="deterministic",
                        centre_frequencies=np.array([f0]))
    t = enc.encode_from_drive(x[None, :], DT).times_in_channel(0)
    isi = np.diff(t)
    assert len(isi) > 20
    hist, edges = np.histogram(isi, bins=200, range=(0.0, 0.05))
    peak = 0.5 * (edges[np.argmax(hist)] + edges[np.argmax(hist) + 1])
    assert abs(peak - 1.0 / f0) < 0.1 / f0, (
        f"ISI mode {peak * 1000:.2f} ms, expected {1000 / f0:.2f} ms")


@pytest.mark.parametrize("sigma", [0.0005, 0.001])
def test_T5_4_jitter_degrades_vector_strength_by_the_gaussian_law(sigma):
    """VS(sigma)/VS(0) = exp(-2 * pi^2 * sigma^2 * f^2).

    Validates both the encoder and the jitter operator used in P2. At f=200 Hz:
      sigma=0.5 ms -> 0.821,  sigma=1.0 ms -> 0.454
    """
    f = 200.0
    x = tone(f, duration=2.0)
    enc = E.PhaseLocked(n_channels=1, threshold=0.05, f_lock=1500.0,
                        refractory=0.001, mode="deterministic",
                        centre_frequencies=np.array([f]))
    clean = enc.encode_from_drive(x[None, :], DT)
    vs0 = metrics.vector_strength(clean.times_in_channel(0), f)
    rng = np.random.default_rng(0)
    ratios = []
    for _ in range(5):
        j = corrupt.jitter(clean, sigma, rng)
        ratios.append(metrics.vector_strength(j.times_in_channel(0), f) / vs0)
    observed = float(np.mean(ratios))
    predicted = np.exp(-2 * np.pi**2 * sigma**2 * f**2)
    assert abs(observed - predicted) < 0.10, (
        f"sigma={sigma * 1000:.1f} ms: observed {observed:.3f}, law predicts {predicted:.3f}")


