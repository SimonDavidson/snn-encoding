def test_vector_strength_extremes():
    """1.0 for perfectly locked events, ~0 for uniformly distributed phase."""
    f = 100.0
    locked = np.arange(50) / f                      # exactly one per cycle
    assert metrics.vector_strength(locked, f) == pytest.approx(1.0, abs=1e-9)
    rng = np.random.default_rng(0)
    uniform = np.sort(rng.uniform(0, 1.0, 5000))
    assert metrics.vector_strength(uniform, f) < 0.1
    assert metrics.vector_strength(np.array([0.01]), f) == 0.0


def test_decoded_information_bounds():
    """Equation (38). Perfect classification of C equiprobable classes gives
    log2(C) bits; chance-level prediction gives zero."""
