def test_T1_1_constant_drive_gives_closed_form_interval():
    """T = tau_m * ln(V_inf / (V_inf - theta)).

    With gain 1, drive 2.0, theta 1.0, tau_m 0.02:
        T = 0.02 * ln(2/1) = 0.0138629 s
    """
    theta, tau_m, u = 1.0, 0.02, 2.0
    expected = tau_m * np.log(u / (u - theta))
    enc = E.LIF(n_channels=1, theta=theta, tau_m=tau_m, gain=1.0, refractory=0.0)
    train = enc.encode_from_drive(constant_drive(u, n_channels=1, duration=1.0), DT)
    t = train.times_in_channel(0)
    assert len(t) > 10, "expected repeated firing under constant drive"
    isi = np.median(np.diff(t))
    assert abs(isi - expected) < 1.5 * DT, (
        f"ISI {isi:.6f} s, closed form predicts {expected:.6f} s")


def test_T1_2_subthreshold_drive_is_silent():
    """V_inf <= theta must produce no events at all."""
    enc = E.LIF(n_channels=1, theta=1.0, tau_m=0.02, gain=1.0, refractory=0.0)
    train = enc.encode_from_drive(constant_drive(0.95, n_channels=1, duration=2.0), DT)
    assert len(train) == 0


def test_T1_3_refractory_caps_the_rate():
    """Firing rate saturates at 1/refractory however large the drive."""
    ref = 0.005
    enc = E.LIF(n_channels=1, theta=1.0, tau_m=0.02, gain=1.0, refractory=ref)
    train = enc.encode_from_drive(constant_drive(500.0, n_channels=1, duration=1.0), DT)
    t = train.times_in_channel(0)
    assert len(t) > 1
    assert np.min(np.diff(t)) >= ref - DT
    assert len(t) <= 1.0 / ref + 1


