def test_T3_1_steady_state_is_permanently_silent():
    """Constant drive: both filters track it, their difference is zero, and no
    event is ever emitted. E2 would settle; E3 must never fire at all."""
    enc = E.TemporalContrast(n_channels=1, theta=0.2,
                             tau_fast=0.001, tau_slow=0.05, refractory=0.0)
    train = enc.encode_from_drive(constant_drive(5.0, n_channels=1, duration=2.0), DT)
    assert len(train) == 0, f"{len(train)} events on constant drive"


def test_T3_2_slow_ramp_separates_E3_from_E2():
    """For a ramp of slope s the steady-state difference is s*(tau_slow -
    tau_fast). With s=2, tau_slow=0.05, tau_fast=0.001 that is 0.098, well
    below theta=0.5, so E3 must be silent. E2 on identical input fires
    repeatedly. If both fire, E3 is not bandpass."""
    s = 2.0
    drive = ramp_drive(s, n_channels=1, duration=2.0)
    e3 = E.TemporalContrast(n_channels=1, theta=0.5,
                            tau_fast=0.001, tau_slow=0.05, refractory=0.0)
    e2 = E.SendOnDelta(n_channels=1, C=0.1, refractory=0.0)
    n3 = len(e3.encode_from_drive(drive, DT))
    n2 = len(e2.encode_from_drive(drive, DT))
    assert n3 == 0, f"E3 emitted {n3} events on a slow ramp"
    assert n2 > 20, f"E2 emitted only {n2} events; check the test signal"


def test_T3_3_difference_of_exponentials_peaks_at_geometric_mean():
    """|H(w)| = |1/(1+jw*tau_f) - 1/(1+jw*tau_s)| peaks at w = 1/sqrt(tau_f*tau_s).

    With tau_f=1 ms, tau_s=50 ms that is 22.5 Hz. Tested on the amplitude of
    the internal difference signal rather than on event count, because event
    count also scales with modulation frequency and is not monotonic in |H|.
    """
    tau_f, tau_s = 0.001, 0.05
    f_peak = 1.0 / (2 * np.pi * np.sqrt(tau_f * tau_s))
    enc = E.TemporalContrast(n_channels=1, theta=1e9,   # never fires; we want the trace
                             tau_fast=tau_f, tau_slow=tau_s, refractory=0.0)
    amplitudes = {}
    for f_mod in (2.0, f_peak, 300.0):
        drive = sine_drive(1.0, f_mod, n_channels=1, duration=2.0)
        _, state = enc.encode_from_drive(drive, DT, return_state=True)
        trim = int(0.5 / DT)            # discard startup
        amplitudes[f_mod] = np.max(np.abs(state["d"][0, trim:]))
    assert amplitudes[f_peak] > amplitudes[2.0]
    assert amplitudes[f_peak] > amplitudes[300.0]


