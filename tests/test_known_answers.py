def test_T4_2_threshold_decays_geometrically_after_a_spike():
    """After an isolated event the threshold follows theta_0 + delta_a * rho^n
    with rho = exp(-dt/tau_a). Asserted on the state trace, not on firing."""
    theta_0, delta_a, tau_a = 1.0, 0.5, 0.05
    rho = np.exp(-DT / tau_a)
    enc = E.ALIF(n_channels=1, theta_0=theta_0, delta_a=delta_a, tau_a=tau_a,
                 tau_m=0.02, gain=1.0, refractory=0.0)
    # brief pulse, then silence: one burst then a long decay to observe
    drive = step_drive(0.0, 3.0, 0.0, n_channels=1, duration=0.02)
    tail = np.zeros((1, int(0.3 / DT)))
    drive = np.hstack([drive, tail])
    train, state = enc.encode_from_drive(drive, DT, return_state=True)
    assert len(train) > 0
    last = int(round(train.time[-1] / DT))
    thr = state["threshold"][0]
    start = last + 2
    window = thr[start:start + int(0.05 / DT)] - theta_0
    assert window[0] > 1e-6, "threshold did not rise after an event"
    predicted = window[0] * rho ** np.arange(len(window))
    np.testing.assert_allclose(window, predicted, rtol=1e-6, atol=1e-9)


def test_T4_3_adaptation_emphasises_onsets():
    """A step drive gives a burst then decay. The ratio of early to late event
    counts exceeds one, and grows with adaptation strength."""
    drive = step_drive(0.0, 3.0, 0.1, n_channels=1, duration=1.0)
    ratios = []
    for delta_a in (0.0, 0.5, 2.0):
        enc = E.ALIF(n_channels=1, theta_0=1.0, delta_a=delta_a, tau_a=0.1,
                     tau_m=0.02, gain=1.0, refractory=0.0)
        t = enc.encode_from_drive(drive, DT).times_in_channel(0)
        early = int(np.sum((t >= 0.10) & (t < 0.15)))
        late = int(np.sum((t >= 0.50) & (t < 0.55)))
        ratios.append(early / max(late, 1))
    assert ratios[0] == pytest.approx(1.0, abs=0.25), "no adaptation, no emphasis"
    assert ratios[1] > 1.1
    assert ratios[2] > ratios[1]


def test_T4_4_adaptation_suppresses_the_steady_state():
    """Sustained firing rate falls monotonically as adaptation strengthens."""
    drive = constant_drive(3.0, n_channels=1, duration=2.0)
    rates = []
    for delta_a in (0.0, 0.25, 1.0, 4.0):
        enc = E.ALIF(n_channels=1, theta_0=1.0, delta_a=delta_a, tau_a=0.1,
                     tau_m=0.02, gain=1.0, refractory=0.0)
        t = enc.encode_from_drive(drive, DT).times_in_channel(0)
        rates.append(int(np.sum(t > 1.0)))       # second half only
    assert np.all(np.diff(rates) <= 0), f"steady-state rates not decreasing: {rates}"
    assert rates[0] > rates[-1]


