def test_F1_centre_frequencies_match_impulse_responses():
    """The spectral peak of each gammatone impulse response sits at its nominal
    centre frequency, within 1 per cent. Equation (4)."""
    fb = Filterbank(n_channels=16, f_min=100.0, f_max=6000.0, sample_rate=FS)
    n = 4096
    for c in range(fb.n_channels):
        h = fb.impulse_response(c, n)
        spectrum = np.abs(np.fft.rfft(h, n=8 * n))
        freqs = np.fft.rfftfreq(8 * n, d=1.0 / FS)
        peak = freqs[np.argmax(spectrum)]
        nominal = fb.centre_frequencies[c]
        assert abs(peak - nominal) / nominal < 0.01, (
            f"channel {c}: peak {peak:.1f} Hz vs nominal {nominal:.1f} Hz")


def test_F2_bandwidths_follow_glasberg_moore():
    """b_c = 1.019 * ERB(f_c), with ERB from equation (5)."""
    fb = Filterbank(n_channels=16, f_min=100.0, f_max=6000.0, sample_rate=FS)
    erb = 24.7 * (0.00437 * fb.centre_frequencies + 1.0)
    np.testing.assert_allclose(fb.bandwidths, 1.019 * erb, rtol=1e-6)


def test_F3_erb_spacing_is_uniform():
    """Centre frequencies uniform on the ERB-rate scale, equation (6),
    ascending, and hitting the endpoints exactly."""
    fb = Filterbank(n_channels=32, f_min=80.0, f_max=7000.0, spacing="erb")
    fc = fb.centre_frequencies
    assert np.all(np.diff(fc) > 0), "centre frequencies must ascend"
    assert abs(fc[0] - 80.0) < 1e-6 and abs(fc[-1] - 7000.0) < 1e-6
    e = 21.4 * np.log10(0.00437 * fc + 1.0)
    steps = np.diff(e)
    assert np.std(steps) / np.mean(steps) < 1e-6


def test_F4_envelope_tracks_amplitude_modulation():
    """The envelope of an AM tone recovers the modulator. Equations (8)-(9)."""
    fb = Filterbank(n_channels=24, f_min=100.0, f_max=6000.0, sample_rate=FS)
    fc_target = 1000.0
    c = int(np.argmin(np.abs(fb.centre_frequencies - fc_target)))
    n = FS
    t = np.arange(n) / FS
    modulator = 1.0 + 0.5 * np.sin(2 * np.pi * 5 * t)
    audio = modulator * np.sin(2 * np.pi * fb.centre_frequencies[c] * t)
    env = fb.envelope(audio, method="hilbert")[c]
    trim = FS // 10                      # discard filter startup transient
    r = np.corrcoef(env[trim:-trim], modulator[trim:-trim])[0, 1]
    assert r > 0.95, f"envelope/modulator correlation {r:.3f}"


def test_F5_subbands_conserve_energy_approximately():
    """Summed subband energy is of the same order as input energy: catches
    normalisation applied twice, or not at all."""
    fb = Filterbank(n_channels=32, f_min=100.0, f_max=6000.0, sample_rate=FS)
    audio = speechlike(duration=1.0)
    sub = fb.subbands(audio)
    ratio = np.sum(sub**2) / np.sum(audio**2)
    assert 0.2 < ratio < 20.0, f"subband/input energy ratio {ratio:.3f}"


